# # [The NEMDE formulation in AEMSim](@id nemde-model)
#
# Every five minutes, NEMDE chooses energy targets, interconnector transfers and FCAS enablement
# from offers, forecasts and measured starting conditions. Energy and FCAS share physical
# capability, so they are co-optimised. AustralianElectricityMarkets builds these inputs into a
# PowerSystems `System`; AustralianElectricityMarketsSimulations (AEMSim) constructs the dispatch
# problem in PowerSimulations (PSI). This documentation describes that reconstruction and identifies
# differences from AEMO's model. It does not claim an exact reproduction of every NEMDE procedure.
#
# ## Reading the formulation
#
# | Chapter | Equations and inputs |
# | --- | --- |
# | [Energy bids and participants](@ref nemde-energy) | Generation, scheduled consumption, battery directions, price referral, availability, ramps and regional balance |
# | [FCAS capability and co-optimisation](@ref nemde-fcas) | The ten services, procurement, offers, scaling, trapezia, joint capacity/ramping, battery regulation and a worked MMSDM interval |
# | [Interconnectors and losses](@ref nemde-interconnectors) | Signed flow, ordered loss segments, regional sharing, MNSP directional offers and pending #183 corrections |
# | [Fast-start dispatch](@ref nemde-fast-start) | Pending #184 preprocessing, profile modes, two-pass commitment, remaining ramp time and distinct violations |
# | [Violations, tie-breaking and prices](@ref nemde-prices) | Generic rows, penalty hierarchy, equal-price bands, fixed-integer duals and raw price recovery |
#
# Each chapter maps mathematical inputs to MMSDM tables and explains coverage. CairoMakie figures
# are generated by Literate from constructed examples; they illustrate geometry without requiring
# a historical cache. The FCAS worked interval preserves an inspected historical example and
# provides reader commands, rather than downloading data during a documentation build.
#
# ## Notation and information timing
#
# | Symbol | Meaning and units |
# | --- | --- |
# | ``u,r,i,b,k`` | Unit, region, interconnector, band, generic constraint |
# | ``s`` | FCAS service index; a subscripted ``s_j`` denotes violation slack |
# | ``h`` | Dispatch interval hours, normally ``5/60`` |
# | ``S`` | System base power in MW; PSI variables use per-unit MW |
# | ``p_u`` | Signed net energy injection in MW |
# | ``q_{u,b}``, ``Q_{u,b}`` | Cleared and offered band MW |
# | ``r_{u,s}`` | Enabled FCAS MW |
# | ``x_i,L_i`` | Signed interconnector flow and loss MW |
# | ``c`` | Energy price in \$/MWh or FCAS price in \$/MW/h |
#
# An MMSDM dispatch timestamp identifies the interval **end**, in fixed AEST. `INITIALMW` is the
# metered starting output, not the preceding dispatch target. `NEMReplayDispatch` uses the meter
# for each historical interval. `NEMLookaheadDispatch` chains solved targets after the first
# interval. Fast-start replay additionally needs previous-interval state, not current outcomes.
# Published `TOTALCLEARED`, RRP and FCAS targets are comparison outputs. A published generic RHS
# is used to reconstruct the invoked network equation; its definition and version still matter.
#
# The physical-unit objective has the shape
#
# ```math
# \min\ h\left(\sum c^{GEN}q^{GEN}-\sum c^{LOAD}q^{LOAD}
# +\sum c^{FCAS}q^{FCAS}+\sum c^{MNSP}q^{MNSP}
# +\mathrm{MPC}\sum_jv_js_j\right)+C_{tie}.
# ```
#
# Generation and FCAS incur offer cost, while controllable consumption earns bid value. Losses
# enter regional balance rather than a separate offer-cost term. The detailed signs, referral,
# limits and slack conditions are defined in the linked chapters. Prices require dual normalisation
# by ``Sh``; mixed-integer loss/direction decisions require the fixed-integer LP described there.
#
# ## Current implementation and pending changes
#
# The current branch supports energy dispatch, all ten FCAS offer types, generic procurement and
# network constraints, battery net-energy ramps, ordered interconnector loss segments, and paired
# MNSP offers. Optional service/network slacks and unconditional ramp/flow slacks have different
# activation rules. Battery state of charge and charge/discharge exclusivity are absent from these
# NEM formulations. FCAS availability reporting and price adjustment procedures remain incomplete.
#
# The chapters label the proposed behavior in [PR #183](https://github.com/ymiftah/AustralianElectricityMarkets.jl/pull/183)
# and [PR #184](https://github.com/ymiftah/AustralianElectricityMarkets.jl/pull/184) separately.
# PR #183 corrects discrete loss anchoring, MNSP regional loss allocation and a narrowly applicable
# annual coefficient omission. #184 adds thermal fast-start replay and separate thermal profile,
# availability and offer violations. Describing those equations here does not merge their code.
#
# For executable teaching examples, continue with [NEMDE as a JuMP model](@ref nemde-jump), then
# the PSI and AEM tutorials. Those deliberately reduced examples introduce the assembly process;
# their equations are not the complete participant and replay formulation documented here.
#
